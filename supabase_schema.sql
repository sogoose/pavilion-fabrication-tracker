-- Per-module site photos / short notes
create table if not exists public.pavilion_module_photos (
  id bigint generated by default as identity primary key,
  project_id text not null,
  rhino_guid text not null,
  object_id text,
  storage_path text not null unique,
  note text not null default '' check (char_length(note) <= 240),
  uploaded_by text,
  created_at timestamptz not null default now()
);

create index if not exists pavilion_module_photos_lookup_idx
  on public.pavilion_module_photos(project_id, rhino_guid, created_at desc);

alter table public.pavilion_module_photos enable row level security;

drop policy if exists "pavilion_module_photos_select" on public.pavilion_module_photos;
create policy "pavilion_module_photos_select"
on public.pavilion_module_photos for select
to anon, authenticated
using (true);

drop policy if exists "pavilion_module_photos_insert" on public.pavilion_module_photos;
create policy "pavilion_module_photos_insert"
on public.pavilion_module_photos for insert
to anon, authenticated
with check (
  project_id = 'pavilion-2026'
  and char_length(coalesce(uploaded_by,'')) between 1 and 80
  and char_length(coalesce(note,'')) <= 240
);

create or replace function public.limit_pavilion_module_photos()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (
    select count(*)
    from public.pavilion_module_photos
    where project_id = new.project_id
      and rhino_guid = new.rhino_guid
  ) >= 5 then
    raise exception 'Maximum 5 photos per module';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_limit_pavilion_module_photos on public.pavilion_module_photos;
create trigger trg_limit_pavilion_module_photos
before insert on public.pavilion_module_photos
for each row execute function public.limit_pavilion_module_photos();
